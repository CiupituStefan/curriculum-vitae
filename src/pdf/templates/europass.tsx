/* eslint-disable jsx-a11y/alt-text -- react-pdf <Image> renders into a PDF and has no alt attribute */
import { Document, Image, Link, Page, Text, View } from "@react-pdf/renderer";
import type { PdfEntry, PdfModel } from "../model";

/*
 * CV following the structure of the European Europass template (personal details, about me,
 * work experience, education and training, language skills with the CEFR grid, digital and
 * other skills). It is NOT an official Europass document, and its footer says so.
 */
const BLUE = "#0b3a82";
const INK = "#1d1d1f";
const MUTED = "#55575c";
const RULE = "#c9d3e6";

const DISCLAIMER = {
  ro: "Structură inspirată de modelul Europass. Document generat de site-ul personal; nu este un document oficial emis prin platforma Europass.",
  en: "Structure inspired by the Europass template. Generated by the personal website; not an official document issued through the Europass platform.",
};

function Heading({ children }: { children: string }) {
  return (
    <View minPresenceAhead={60} style={{ marginTop: 14, marginBottom: 6 }}>
      <Text style={{ fontSize: 10.5, fontWeight: 700, color: BLUE, textTransform: "uppercase", letterSpacing: 0.6 }}>
        {children}
      </Text>
      <View style={{ height: 1, backgroundColor: RULE, marginTop: 3 }} />
    </View>
  );
}

function Entry({ entry, skillsLabel }: { entry: PdfEntry; skillsLabel?: string }) {
  return (
    <View style={{ marginBottom: 9 }}>
      <View wrap={false}>
        <Text style={{ fontSize: 8, color: MUTED }}>
          {[entry.period, entry.location].filter(Boolean).join("  ·  ")}
        </Text>
        <Text style={{ fontSize: 10, fontWeight: 700, color: INK, marginTop: 1.5, textTransform: "uppercase" }}>
          {entry.title}
        </Text>
        {entry.organization ? <Text style={{ fontSize: 9, color: BLUE, marginTop: 1 }}>{entry.organization}</Text> : null}
      </View>
      {entry.summary ? <Text style={{ fontSize: 8.8, lineHeight: 1.5, marginTop: 3 }}>{entry.summary}</Text> : null}
      {entry.bullets.map((bullet, index) => (
        <View key={index} wrap={false} style={{ flexDirection: "row", marginTop: 2 }}>
          <Text style={{ width: 9, fontSize: 8.8 }}>•</Text>
          <Text style={{ flex: 1, fontSize: 8.8, lineHeight: 1.45 }}>{bullet}</Text>
        </View>
      ))}
      {skillsLabel && entry.tags.length > 0 ? (
        <Text style={{ fontSize: 8, color: MUTED, marginTop: 3, lineHeight: 1.4 }}>
          {skillsLabel}: {entry.tags.join(", ")}
        </Text>
      ) : null}
    </View>
  );
}

const cell = { fontSize: 8, paddingVertical: 3, paddingHorizontal: 2, textAlign: "center" as const };

export function EuropassCv({ model, photo }: { model: PdfModel; photo?: Buffer | null }) {
  const L = model.labels;
  const isRo = model.locale === "ro";
  const foreign = model.languages.filter((language) => !language.native);
  const native = model.languages.filter((language) => language.native);

  return (
    <Document title={`${model.name} — CV`} author={model.name} subject={model.headline} language={model.locale} creator={model.siteUrl} producer={model.siteUrl}>
      <Page size="A4" style={{ fontFamily: "Inter", color: INK, paddingTop: 40, paddingBottom: 58, paddingHorizontal: 46 }}>
        <View style={{ flexDirection: "row", alignItems: "center", paddingBottom: 10, borderBottomWidth: 2, borderBottomColor: BLUE }}>
          {photo ? <Image src={photo} style={{ width: 58, height: 58, marginRight: 14 }} /> : null}
          <View style={{ flex: 1 }}>
            <Text style={{ fontSize: 20, fontWeight: 700, color: BLUE }}>{model.name}</Text>
            <Text style={{ fontSize: 9.5, marginTop: 3 }}>{model.headline}</Text>
            <View style={{ flexDirection: "row", flexWrap: "wrap", marginTop: 5 }}>
              {model.contact.map((item) => (
                <Text key={item.label} style={{ fontSize: 8, marginRight: 10, marginBottom: 2 }}>
                  <Text style={{ color: MUTED }}>{item.label}: </Text>
                  {item.href ? <Link src={item.href} style={{ color: INK, textDecoration: "none" }}>{item.value}</Link> : item.value}
                </Text>
              ))}
            </View>
          </View>
        </View>

        <Heading>{isRo ? "Despre mine" : "About me"}</Heading>
        <Text style={{ fontSize: 9, lineHeight: 1.55 }}>{model.summary}</Text>

        <Heading>{isRo ? "Experiența profesională" : "Work experience"}</Heading>
        {model.experience.map((entry, index) => (
          <Entry key={index} entry={entry} skillsLabel={L.skillsUsed} />
        ))}

        <Heading>{isRo ? "Educație și formare profesională" : "Education and training"}</Heading>
        {[...model.education, ...model.courses].map((entry, index) => (
          <Entry key={index} entry={entry} />
        ))}

        <Heading>{isRo ? "Competențe lingvistice" : "Language skills"}</Heading>
        {native.length > 0 ? (
          <Text style={{ fontSize: 8.8, marginBottom: 5 }}>
            <Text style={{ color: MUTED }}>{isRo ? "Limbă(i) maternă(e): " : "Mother tongue(s): "}</Text>
            {native.map((language) => language.name.toUpperCase()).join(", ")}
          </Text>
        ) : null}
        {foreign.length > 0 ? (
          <View wrap={false} style={{ borderWidth: 0.8, borderColor: RULE }}>
            <View style={{ flexDirection: "row", backgroundColor: "#eef2f9" }}>
              <Text style={{ ...cell, width: "22%", textAlign: "left" }}> </Text>
              {foreign[0]!.levels.map((level) => (
                <Text key={level.label} style={{ ...cell, width: "15.6%", color: BLUE, fontWeight: 600 }}>
                  {level.label}
                </Text>
              ))}
            </View>
            {foreign.map((language) => (
              <View key={language.name} style={{ flexDirection: "row", borderTopWidth: 0.8, borderTopColor: RULE }}>
                <Text style={{ ...cell, width: "22%", textAlign: "left", fontWeight: 700 }}>{language.name.toUpperCase()}</Text>
                {language.levels.map((level) => (
                  <Text key={level.label} style={{ ...cell, width: "15.6%" }}>
                    {level.value || "–"}
                  </Text>
                ))}
              </View>
            ))}
          </View>
        ) : null}
        <Text style={{ fontSize: 7.2, color: MUTED, marginTop: 3 }}>
          {isRo
            ? "Niveluri: A1 și A2 Utilizator de bază · B1 și B2 Utilizator independent · C1 și C2 Utilizator experimentat"
            : "Levels: A1 and A2 Basic user · B1 and B2 Independent user · C1 and C2 Proficient user"}
        </Text>

        <Heading>{isRo ? "Competențe digitale și tehnice" : "Digital and technical skills"}</Heading>
        {model.skills.map((group) => (
          <View key={group.group} style={{ marginBottom: 5 }} wrap={false}>
            <Text style={{ fontSize: 8.8, fontWeight: 700 }}>{group.group}</Text>
            <Text style={{ fontSize: 8.6, lineHeight: 1.45 }}>{group.items.join(" | ")}</Text>
          </View>
        ))}

        <Heading>{isRo ? "Certificări" : "Certifications"}</Heading>
        {model.certifications.map((group) => (
          <View key={group.group} style={{ marginBottom: 5 }} wrap={false}>
            <Text style={{ fontSize: 8.8, fontWeight: 700 }}>{group.group}</Text>
            <Text style={{ fontSize: 8.4, lineHeight: 1.45 }}>{group.items.join(" | ")}</Text>
          </View>
        ))}

        {model.projects.length + model.otherProjects.length > 0 ? <Heading>{isRo ? "Proiecte" : "Projects"}</Heading> : null}
        {model.projects.map((project) => (
          <View key={project.title} style={{ marginBottom: 5 }} wrap={false}>
            <Text style={{ fontSize: 8.8, fontWeight: 700 }}>
              {project.title} <Text style={{ fontWeight: 400, color: MUTED }}>({project.year})</Text>
            </Text>
            <Text style={{ fontSize: 8.5, lineHeight: 1.45 }}>{project.summary}</Text>
          </View>
        ))}

        {model.otherProjects.length > 0 ? (
          <Text style={{ fontSize: 8.5, lineHeight: 1.5, marginTop: 2 }}>
            <Text style={{ fontWeight: 700 }}>{isRo ? "Alte proiecte: " : "Other projects: "}</Text>
            {model.otherProjects.join(" | ")}
          </Text>
        ) : null}

        {model.volunteering.length > 0 ? <Heading>{isRo ? "Voluntariat" : "Volunteering"}</Heading> : null}
        {model.volunteering.map((entry, index) => (
          <Entry key={index} entry={entry} />
        ))}

        {model.awards.length > 0 ? <Heading>{isRo ? "Premii și distincții" : "Honours and awards"}</Heading> : null}
        {model.awards.map((entry, index) => (
          <Entry key={index} entry={entry} />
        ))}

        <Heading>{isRo ? "Competențe sociale și organizatorice" : "Social and organisational skills"}</Heading>
        <Text style={{ fontSize: 8.8, lineHeight: 1.5 }}>{model.personalSkills.join(", ")}</Text>

        {model.otherInfo.length > 0 ? <Heading>{isRo ? "Informații suplimentare" : "Additional information"}</Heading> : null}
        {model.otherInfo.map((info) => (
          <Text key={info.title} style={{ fontSize: 8.8, lineHeight: 1.5 }}>
            <Text style={{ fontWeight: 700 }}>{info.title}: </Text>
            {info.description}
          </Text>
        ))}

        <View fixed style={{ position: "absolute", bottom: 20, left: 46, right: 46, flexDirection: "row", justifyContent: "space-between" }}>
          <Text style={{ fontSize: 6.8, color: MUTED, width: "85%" }}>{DISCLAIMER[model.locale]}</Text>
          <Text style={{ fontSize: 7.5, color: MUTED }} render={({ pageNumber, totalPages }) => `${pageNumber} / ${totalPages}`} />
        </View>
      </Page>
    </Document>
  );
}
