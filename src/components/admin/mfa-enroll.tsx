"use client";

import { LoaderCircle, ShieldCheck } from "lucide-react";
import { useState, useTransition } from "react";
import { confirmMfaEnrollmentAction, startMfaEnrollmentAction, type EnrollState } from "@/app/admin/actions";
import { Notice } from "./notice";

/** Guided TOTP enrollment: scan the QR code, then confirm with a first 6-digit code. */
export function MfaEnroll() {
  const [state, setState] = useState<EnrollState>({ step: "idle" });
  const [code, setCode] = useState("");
  const [error, setError] = useState<string | null>(null);
  const [pending, startTransition] = useTransition();

  if (state.step === "done") {
    return <Notice tone="success">Verificarea în doi pași este activă. De acum, la autentificare îți va fi cerut și codul din aplicație.</Notice>;
  }

  if (state.step === "idle") {
    return (
      <div className="space-y-3">
        {state.error ? <Notice tone="danger">Nu am putut porni activarea ({state.error}).</Notice> : null}
        <button type="button" className="btn btn-primary" disabled={pending} onClick={() => startTransition(async () => setState(await startMfaEnrollmentAction()))}>
          {pending ? <LoaderCircle size={16} aria-hidden="true" className="animate-spin" /> : <ShieldCheck size={16} aria-hidden="true" />}
          Activează verificarea în doi pași
        </button>
      </div>
    );
  }

  return (
    <div className="space-y-5">
      <ol className="list-decimal space-y-1 pl-5 text-sm text-muted">
        <li>Deschide o aplicație de autentificare (Google Authenticator, Microsoft Authenticator, 1Password, Bitwarden etc.).</li>
        <li>Scanează codul QR sau introdu manual cheia de mai jos.</li>
        <li>Scrie codul de 6 cifre afișat de aplicație și confirmă.</li>
      </ol>
      {/* eslint-disable-next-line @next/next/no-img-element -- inline SVG data URL generated by Supabase */}
      <img src={state.qrCode} alt="Cod QR pentru aplicația de autentificare" width={200} height={200} className="rounded-xl border border-line bg-white p-2" />
      <div>
        <p className="text-xs font-semibold uppercase tracking-wider text-muted">Cheie pentru introducere manuală</p>
        <code className="mt-1 block break-all rounded-lg bg-surface-2 px-3 py-2 text-sm">{state.secret}</code>
      </div>
      <form
        className="flex flex-wrap items-end gap-3"
        onSubmit={(event) => {
          event.preventDefault();
          setError(null);
          startTransition(async () => {
            const result = await confirmMfaEnrollmentAction(state.factorId, code);
            if (result.ok) setState({ step: "done" });
            else setError(result.error === "rate_limited" ? "Prea multe încercări. Așteaptă 15 minute." : "Codul nu este corect. Verifică ora telefonului și încearcă din nou.");
          });
        }}
      >
        <div>
          <label htmlFor="mfa-code" className="text-sm font-medium">
            Cod de confirmare
          </label>
          <input id="mfa-code" inputMode="numeric" autoComplete="one-time-code" pattern="[0-9]{6}" maxLength={6} required value={code} onChange={(e) => setCode(e.target.value)} className="field mt-1 w-40 text-center text-xl tracking-[0.3em] tabular-nums" />
        </div>
        <button type="submit" className="btn btn-primary" disabled={pending}>
          {pending ? <LoaderCircle size={16} aria-hidden="true" className="animate-spin" /> : null}
          Confirmă și activează
        </button>
      </form>
      {error ? <Notice tone="danger">{error}</Notice> : null}
    </div>
  );
}
